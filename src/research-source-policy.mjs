export function canonicalShader(source){
  if(typeof source!=='string')throw new TypeError('Shader source must be text');
  // Normalization catches trivial paste, whitespace and comment variations.
  // This signature filter is not a copyright or semantic similarity classifier.
  return source.replace(/\/\*[\s\S]*?\*\/|\/\/[^\n]*/g,'').replace(/\s+/g,'');
}
export function identifyExampleShader(source){
  const normalized=canonicalShader(source);
  return ORIGINAL_DEMO_SIGNATURES.find(item=>{
    if(normalized.includes(item.head)&&normalized.includes(item.tail))return true;
    // Fragments from distinct positions tolerate minor edits, reordered helper
    // code, and embedded gallery source while rejecting a substantial reuse.
    const hits=item.fragments.reduce((n,fragment)=>n+Number(normalized.includes(fragment)),0);
    return hits>=Math.ceil(item.fragments.length*.67);
  })?.id||null;
}
export function assertResearchEligibleShader({body,identifier,attribution}={}){
  if(typeof body!=='string'||!body.trim())throw new TypeError('Shader body is required');
  const demo=identifyExampleShader(body);
  if(demo||ORIGINAL_DEMO_SIGNATURES.some(item=>item.id===identifier)||
    /yoheinishitsuji/i.test(String(attribution||'')))
    throw new TypeError('Example-gallery shaders are excluded from research and manuscript export'+(demo?': '+demo:''));
  return true;
}
